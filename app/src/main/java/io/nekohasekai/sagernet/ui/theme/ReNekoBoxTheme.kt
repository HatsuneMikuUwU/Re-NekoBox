@OptIn(ExperimentalMaterial3ExpressiveApi::class)
@Composable
fun ReNekoBoxTheme(
    content: @Composable () -> Unit,
) {
    val context = LocalContext.current
    AppearanceStore.init(context)
    val settings by AppearanceStore.settings.collectAsState()

    val darkTheme = when (settings.mode) {
        ThemeMode.SYSTEM -> isSystemInDarkTheme()
        ThemeMode.LIGHT -> false
        ThemeMode.DARK -> true
    }

    val dynamicSupported = Build.VERSION.SDK_INT >= Build.VERSION_CODES.S
    val systemSeed = if (dynamicSupported) colorResource(android.R.color.system_accent1_500) else null
    val effectiveSeed = systemSeed.takeIf { settings.dynamicColor } ?: settings.seedColor

    val themeState = rememberDynamicMaterialThemeState(
        seedColor = effectiveSeed,
        isDark = darkTheme,
        isAmoled = darkTheme && settings.amoled,
        style = settings.paletteStyle.toKolor(),
        contrastLevel = settings.contrast.toDouble().coerceIn(-1.0, 1.0),
    )

    val colorAnimSpec = remember(settings.colorAnimationMs) {
        tween<Color>(durationMillis = settings.colorAnimationMs)
    }

    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as? Activity)?.window
            if (window != null) {
                @Suppress("DEPRECATION")
                window.statusBarColor = Color.Transparent.toArgb()
                @Suppress("DEPRECATION")
                window.navigationBarColor = Color.Transparent.toArgb()
                val controller = WindowCompat.getInsetsController(window, view)
                controller.isAppearanceLightStatusBars = !darkTheme
                controller.isAppearanceLightNavigationBars = !darkTheme
            }
        }
    }

    val baseDensity = LocalDensity.current
    val scaledDensity = remember(baseDensity, settings.uiScale, settings.fontScale) {
        Density(
            density = baseDensity.density * settings.uiScale,
            fontScale = baseDensity.fontScale * settings.fontScale,
        )
    }

    CompositionLocalProvider(LocalDensity provides scaledDensity) {
        DynamicMaterialExpressiveTheme(
            state = themeState,
            motionScheme = MotionScheme.expressive(),
            shapes = ReNekoBoxExpressiveShapes,
            typography = ReNekoBoxExpressiveTypography,
            animate = settings.animateColorChange,
            animationSpec = colorAnimSpec,
            content = content,
        )
    }
}
